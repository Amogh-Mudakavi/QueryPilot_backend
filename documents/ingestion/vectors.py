"""
Chroma vector store for QueryPilot.

Responsibilities
----------------
1. Store text chunks generated by the StructureAwareChunker.
2. Store table metadata generated during table ingestion.
3. Store document-level metadata for planner routing.
4. Delete all vectors belonging to a document.

This file should NOT know anything about:
    - LlamaParse
    - Chunking logic
    - SQLite tables

It only stores and retrieves embeddings.
"""

import chromadb

from django.conf import settings
from sentence_transformers import SentenceTransformer


KNOWLEDGE_COLLECTION = "querypilot_knowledge"
DOCUMENT_COLLECTION = "querypilot_document_metadata"


class VectorStore:
    print("STORE_DOCUMENT_PROFILE CALLED")
    """
    Central Chroma interface.

    QueryPilot uses:

        querypilot_knowledge
            - text chunks
            - table metadata

        querypilot_document_metadata
            - one document profile per document
    """

    _client = None
    _embedder = None

    @classmethod
    def get_client(cls):

        if cls._client is None:

            cls._client = chromadb.PersistentClient(
                path=str(
                    settings.BASE_DIR
                    / "storage"
                    / "chroma"
                )
            )

        return cls._client

    @classmethod
    def get_embedder(cls):

        if cls._embedder is None:

            cls._embedder = SentenceTransformer(
                "mixedbread-ai/mxbai-embed-large-v1"
            )

        return cls._embedder

    @classmethod
    def knowledge_collection(cls):

        return (
            cls.get_client()
            .get_or_create_collection(
                KNOWLEDGE_COLLECTION
            )
        )

    @classmethod
    def document_collection(cls):

        return (
            cls.get_client()
            .get_or_create_collection(
                DOCUMENT_COLLECTION
            )
        )

    @classmethod
    def embed(
        cls,
        texts,
    ):

        model = cls.get_embedder()

        return model.encode(
            texts,
            normalize_embeddings=True,
        ).tolist()

    @classmethod
    def store_chunks(
        cls,
        workspace_id,
        document_id,
        chunks,
    ):

        if not chunks:
            return

        collection = (
            cls.knowledge_collection()
        )

        documents = [
            chunk["text"]
            for chunk in chunks
        ]

        ids = [
            f"doc_{document_id}_chunk_{chunk['chunk_index']}"
            for chunk in chunks
        ]

        metadatas = []

        for chunk in chunks:

            metadatas.append(
                {
                    "workspace_id": workspace_id,
                    "document_id": document_id,
                    "type": "text",
                    "chunk_index": chunk[
                        "chunk_index"
                    ],
                    "page_start": chunk[
                        "page_start"
                    ],
                    "page_end": chunk[
                        "page_end"
                    ],
                    "heading": chunk[
                        "heading"
                    ],
                }
            )

        collection.add(
            ids=ids,
            documents=documents,
            embeddings=cls.embed(
                documents
            ),
            metadatas=metadatas,
        )

    @classmethod
    def store_table_metadata(
        cls,
        workspace_id,
        document_id,
        table_name,
        summary,
    ):

        collection = (
            cls.knowledge_collection()
        )

        collection.add(
            ids=[
                f"{table_name}_metadata"
            ],
            documents=[
                summary
            ],
            embeddings=cls.embed(
                [summary]
            ),
            metadatas=[
                {
                    "workspace_id": workspace_id,
                    "document_id": document_id,
                    "type": "table",
                    "table_name": table_name,
                }
            ],
        )

    @classmethod
    def store_document_profile(
        cls,
        workspace_id,
        document_id,
        document_name,
        profile_text,
    ):
        """
        One profile per document.

        Used by planner.
        """

        collection = (
            cls.document_collection()
        )

        collection.upsert(
            ids=[
                f"document_{document_id}"
            ],
            documents=[
                profile_text
            ],
            embeddings=cls.embed(
                [profile_text]
            ),
            metadatas=[
                {
                    "workspace_id": workspace_id,
                    "document_id": document_id,
                    "document_name": document_name,
                    "type": "document_profile",
                }
            ],
        )

    @classmethod
    def delete_document(
        cls,
        document_id,
    ):

        cls.knowledge_collection().delete(
            where={
                "document_id": document_id
            }
        )

        cls.document_collection().delete(
            where={
                "document_id": document_id
            }
        )